export function getRelatedProducts(product: Product, limit = 4) {
  return mockProducts
    .filter(
      (candidate) =>
        candidate.id !== product.id &&
        candidate.isActive &&
        candidate.categorySlug === product.categorySlug,
    )
    .slice(0, limit);
}
